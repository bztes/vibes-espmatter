import { firmware } from '../core/services';
import type { FeatureDef, FeatureIssue, GenerateContext, DevicePage } from '../../types';
import { cString } from '../../util';
import webUiCpp from './firmware/espm_web_ui.cpp?raw';
import iconSvg from './icon/app-icon.svg?raw';
import iconPng from './icon/app-icon-192.png?inline';
import { webServer } from '../http-server/services';

/**
 * The device web interface: the pages the chip's features register (`devicePages`), each a layout
 * with the panels the features register (`devicePanels`), compiled from Svelte by the build server. Comes with the
 * frame of every page (`device-ui/`: login, header with the page menu, the API client) and serves the
 * pages, their web app manifests and the app icon through the HTTP server.
 *
 * Pages can be added to the home screen like an app. Not a full PWA (no service worker, no
 * "Install" button in Chrome) – browsers only allow that over HTTPS, and the device serves plain
 * HTTP.
 */
export default {
	id: 'web_ui',
	dir: 'web-ui',
	name: 'Web interface',
	description: 'Pages on the device for the features that bring one.',
	category: 'ui',
	validate({ pages }) {
		const list = pages();
		if (!list.length) return ['No feature of this board brings a page yet.'];
		const errors: string[] = [];
		for (const page of list) {
			if (!PAGE_ID.test(page.id)) errors.push(`Invalid page id “${page.id}”.`);
			if (list.filter((p) => p.id === page.id).length > 1)
				errors.push(`Two pages have the id “${page.id}”.`);
		}
		const paths = list.map((p) => p.path);
		for (const path of new Set(paths.filter((p, i) => paths.indexOf(p) !== i)))
			errors.push(`Two pages are served at “${path}”.`);
		return [...new Set(errors)];
	},
	activate({ use, pages }) {
		use(webServer);
		use(firmware).register(() => {
			const list = pages();
			const sym = (id: string) => `${id}_html_gz`;
			return {
				sources: {
					'espm_web_ui.cpp': webUiCpp,
					'espm_web_ui_pages.h': `// Generated by vibes-espmatter – the pages of the web interface.
#pragma once
${list.map((p) => `extern const char ${sym(p.id)}_start[] asm("_binary_${sym(p.id)}_start");\nextern const char ${sym(p.id)}_end[] asm("_binary_${sym(p.id)}_end");`).join('\n')}

static const struct {
    const char *path;
    const char *start;
    const char *end;
    const char *manifest;
} k_pages[] = {
${list.map((p) => `    {${cString(p.path)}, ${sym(p.id)}_start, ${sym(p.id)}_end, ${cString(webManifest(p))}},`).join('\n')}
};
`,
					'espm_icon.cpp': iconCpp()
				},
				hooks: {
					globals: ['void mesp_web_ui_register_web();'],
					preStart: ['mesp_web_ui_register_web();']
				}
			};
		});
	}
} satisfies FeatureDef;

/** Page ids: file names (`main/<id>.html.gz`) and C symbols. */
const PAGE_ID = /^[a-z][a-z0-9_]*$/;

/** The "Path" setting of a page (`path`): one segment, not the API's, and no other page's. */
export function checkPagePath({ config, pages }: GenerateContext): FeatureIssue[] {
	const path = String(config.path);
	const issues: FeatureIssue[] = [];
	if (path.length > 32)
		issues.push({ field: 'path', message: 'Path must be at most 32 characters.' });
	else if (path && !/^\/(?!api$)[a-z0-9-]*$/.test(path))
		issues.push({
			field: 'path',
			message: 'Path: a / and lowercase letters, digits and dashes (not /api).'
		});
	else if (pages().filter((p) => p.path === path).length > 1)
		issues.push({ field: 'path', message: `Another page is served at “${path}” too.` });
	return issues;
}

/** Colors of the device web interface (`device-ui/theme.css`, light theme). */
const BACKGROUND = '#f6f7f9';

/** The web app manifest of a page, with the app icon. */
function webManifest(page: DevicePage): string {
	return JSON.stringify({
		id: page.path,
		name: page.appName,
		short_name: page.appName,
		start_url: page.path,
		scope: '/',
		display: 'standalone',
		background_color: BACKGROUND,
		theme_color: BACKGROUND,
		icons: [
			{ src: '/icon.svg', type: 'image/svg+xml', sizes: 'any' },
			{ src: '/icon.png', type: 'image/png', sizes: '192x192' },
			// The icon is full-bleed with its symbol inside the safe zone.
			{ src: '/icon.png', type: 'image/png', sizes: '192x192', purpose: 'maskable' }
		]
	});
}

/** The app icon as C data, served at `/icon.svg` and `/icon.png`. */
function iconCpp(): string {
	const png = Uint8Array.from(atob(iconPng.slice(iconPng.indexOf(',') + 1)), (ch) =>
		ch.charCodeAt(0)
	);
	const rows: string[] = [];
	for (let i = 0; i < png.length; i += 24) {
		rows.push(
			'    ' +
				Array.from(png.subarray(i, i + 24), (b) => `0x${b.toString(16).padStart(2, '0')}`).join(',')
		);
	}
	return `// Generated by vibes-espmatter – the app icon of the device web interface.
#include <cstddef>
#include <cstdint>

extern const char mesp_icon_svg[] = ${cString(iconSvg.trim())};

extern const uint8_t mesp_icon_png[] = {
${rows.join(',\n')}
};
extern const size_t mesp_icon_png_len = sizeof(mesp_icon_png);
`;
}
