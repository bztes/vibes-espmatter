const PROJECT_CONFIG_H = `// Generated by vibes-espmatter – CHIP project configuration for the commissioner.
#pragma once

#include <sdkconfig.h>

#ifndef CONFIG_ESP_MATTER_ENABLE_MATTER_SERVER
#ifdef CONFIG_ESP_MATTER_COMMISSIONER_ENABLE
#define CHIP_DEVICE_CONFIG_ENABLE_COMMISSIONER_DISCOVERY 1
#endif
// Number of devices the controller can be connected to simultaneously
#define CHIP_CONFIG_CONTROLLER_MAX_ACTIVE_DEVICES 8
#endif
`;

const defaults = () => ({ attestation: 'dcl', fabricId: 1, nodeId: 112233 });
export type MatterControllerConfig = ReturnType<typeof defaults>;

const validate: Validate<MatterControllerConfig> = ({ config }) => {
	const fabricId = Number(config.fabricId);
	const nodeId = Number(config.nodeId);
	const errors: FeatureIssue<MatterControllerConfig>[] = [];
	if (!ATTESTATION.some((o) => o.value === config.attestation))
		errors.push({
			field: 'attestation',
			message: 'Device attestation trust store: invalid option.'
		});
	if (!(fabricId >= 1 && fabricId <= 65535))
		errors.push({ field: 'fabricId', message: 'Fabric ID must be between 1 and 65535.' });
	if (!(nodeId >= 1 && nodeId <= 0xfffffff))
		errors.push({
			field: 'nodeId',
			message: `Controller node ID must be between 1 and ${0xfffffff}.`
		});
	return errors;
};

/**
 * Matter commissioner/controller: the "coordinator" of the hub. Commissions devices into its
 * own fabric (over BLE → Thread or Wi-Fi, or on-network), keeps a registry of them and subscribes
 * to what they report (buttons, battery, sensors, on/off).
 *
 * Devices are paired through its `/api/matter/…` on the HTTP server: list, pair, control and
 * remove devices, their values and button events, and which endpoints each user may see and
 * control (`/api/matter/access`, the access rule other features like timers go through). Without the HTTP
 * server it keeps the devices paired before, e.g. for automations, but can't pair new ones. Pairing over
 * Thread needs Matter controller Thread (`matter_controller_thread`). Its panels: the devices on the admin dashboard,
 * tiles on the user dashboard (with who gets which endpoints on the admin dashboard).
 */
export default {
	id: 'matter_controller',
	dir: 'matter-controller',
	name: 'Matter controller',
	description: 'Pairs and controls Matter devices in the hub’s own fabric.',
	category: 'matter',
	framework: 'esp-matter',
	chips: ['esp32', 'esp32s3', 'esp32c3', 'esp32c6'],
	defaults,
	validate,
	activate(ctx) {
		const { use, find, config, has } = ctx;
		use(network);
		const dashboard = has('user_dashboard');
		use(configuratorEditors).register(Editor);
		use(firmware).register(() => ({
			sdkconfig: {
				CONFIG_BT_ENABLED: true,
				CONFIG_BT_NIMBLE_ENABLED: true,
				CONFIG_ENABLE_ESP32_BLE_CONTROLLER: true,
				// A commissioner needs BLE for every pairing – never free it after the first one.
				CONFIG_USE_BLE_ONLY_FOR_COMMISSIONING: false,
				CONFIG_ESP_MATTER_ENABLE_MATTER_SERVER: false,
				CONFIG_ENABLE_CHIP_CONTROLLER_BUILD: true,
				CONFIG_ESP_MATTER_CONTROLLER_ENABLE: true,
				CONFIG_ESP_MATTER_COMMISSIONER_ENABLE: true,
				[config.attestation === 'test'
					? 'CONFIG_TEST_ATTESTATION_TRUST_STORE'
					: 'CONFIG_DCL_ATTESTATION_TRUST_STORE']: true,
				CONFIG_BUILD_CHIP_TESTS: false,
				CONFIG_ENABLE_OTA_REQUESTOR: false,
				CONFIG_CHIP_PROJECT_CONFIG: 'main/matter_project_config.h',
				CONFIG_NUM_UDP_ENDPOINTS: 16,
				CONFIG_WIFI_NETWORK_COMMISSIONING_DRIVER: false,
				CONFIG_ENABLE_EXTENDED_DISCOVERY: true,
				CONFIG_CHIP_TASK_STACK_SIZE: 15360,
				CONFIG_ESP_MAIN_TASK_STACK_SIZE: 8192,
				CONFIG_MBEDTLS_HKDF_C: true
			},
			defines: {
				MESP_CONTROLLER_NODE_ID: Number(config.nodeId),
				MESP_FABRIC_ID: Number(config.fabricId)
			},
			sources: {
				'espm_matter.cpp': matterCpp,
				'espm_subscriptions.cpp': subscriptionsCpp,
				'espm_matter.h': matterH,
				'espm_matter_registry.h': matterRegistryH,
				'matter_project_config.h': PROJECT_CONFIG_H,
				'espm_ble_fix.c': bleFixC
			},
			linkOptions: ['-Wl,--wrap=ble_gattc_exchange_mtu', '-Wl,--wrap=peer_find'],
			hooks: {
				includes: ['#include "espm_matter.h"'],
				preStart: ['mesp_matter_init();', 'mesp_matter_subscriptions_init();'],
				postStart: ['mesp_matter_start_controller();', 'mesp_matter_subscriptions_start();']
			},
			notes: [
				...(psramMode(ctx) === 'none'
					? ['No PSRAM selected: a Matter controller with Thread border router may run out of RAM.']
					: []),
				...(has('http_server')
					? []
					: [
							'Matter controller without the HTTP server: it can’t pair new devices, only use those paired before.'
						])
			]
		}));
		find(webServer)?.register({
			api,
			sources: {
				'espm_matter_web.cpp': matterWebCpp,
				'espm_matter_web.h': matterWebH,
				'espm_matter_access.cpp': accessCpp
			},
			init: 'mesp_matter_register_web'
		});
		const panels = find(devicePanels);
		panels?.register({
			id: 'matter',
			title: 'Matter devices',
			file: 'MatterPanel.svelte',
			area: 'main',
			section: 'devices'
		});
		// Users who aren't admins only see the user dashboard.
		if (dashboard)
			panels?.register(
				{
					id: 'tiles',
					title: 'Dashboard',
					file: 'TilesPanel.svelte',
					page: USER_DASHBOARD,
					area: 'main'
				},
				{
					id: 'access',
					title: 'Dashboard access',
					file: 'AccessPanel.svelte',
					area: 'main',
					section: 'users'
				}
			);
	}
} satisfies FeatureDef<MatterControllerConfig>;
