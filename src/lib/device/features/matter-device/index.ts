import { configuratorEditors, firmware } from '../core/services';
import type { FeatureDef, FeatureIssue, Validate } from '../../types';
import { cString, fnv1a } from '../../util';
import Editor from './configurator/Editor.svelte';
import nodeCpp from './firmware/espm_node.cpp?raw';
import nodeH from './firmware/espm_node.h?raw';
import {
	formatManualCode,
	manualPairingCode,
	qrCodePayload,
	toValidPasscode,
	validPasscode
} from './onboarding';
import { network } from '../wifi/services';

/** Setup code of a chip: the configured one, or one derived from the device and chip name. */
export function setupCode(
	config: Record<string, unknown>,
	projectName: string,
	chipId: string
): { passcode: number; discriminator: number } {
	const passcode = Number(config.passcode);
	const discriminator = Number(config.discriminator);
	return {
		passcode: passcode > 0 ? passcode : toValidPasscode(fnv1a(`${projectName}/${chipId}/passcode`)),
		discriminator:
			discriminator >= 0 ? discriminator : fnv1a(`${projectName}/${chipId}/discriminator`) & 0xfff
	};
}

const projectConfigH = (vendor: string, product: string) =>
	`// Generated by vibes-espmatter – CHIP project configuration of the Matter device.
#pragma once

#define CHIP_DEVICE_CONFIG_DEVICE_VENDOR_NAME ${cString(vendor)}
#define CHIP_DEVICE_CONFIG_DEVICE_PRODUCT_NAME ${cString(product)}
`;

const defaults = () => ({
	passcode: 0,
	discriminator: -1,
	vendorName: 'vibes-espmatter',
	resetGpio: 0
});
export type MatterDeviceConfig = ReturnType<typeof defaults>;

const validate: Validate<MatterDeviceConfig> = ({ config, has }) => {
	const discriminator = Number(config.discriminator);
	const vendorName = String(config.vendorName);
	const errors: FeatureIssue<MatterDeviceConfig>[] = [];
	if (!(discriminator >= -1 && discriminator <= 4095))
		errors.push({
			field: 'discriminator',
			message: 'Discriminator must be between -1 and 4095.'
		});
	if (!vendorName.trim()) errors.push({ field: 'vendorName', message: 'Vendor name is required.' });
	else if (vendorName.length > 32)
		errors.push({ field: 'vendorName', message: 'Vendor name must be at most 32 characters.' });
	const passcode = Number(config.passcode);
	if (passcode !== 0 && !validPasscode(passcode))
		errors.push({
			field: 'passcode',
			message: 'Setup passcode: 1–99999998, not a trivial one like 12345678 or 11111111.'
		});
	if (has('matter_controller'))
		errors.push('A board is either a Matter device or a Matter controller (hub), not both.');
	return errors;
};

/**
 * A Matter device that controllers (Apple Home, Google Home, Home Assistant, a Matter Thread Hub …)
 * pair with: the node with its root endpoint, the setup code and a factory-reset button. Other
 * features add the endpoints (e.g. the Panasonic heat pump).
 */
export default {
	id: 'matter_device',
	dir: 'matter-device',
	name: 'Matter device',
	description: 'A Matter device for Apple Home, Google Home or Home Assistant.',
	category: 'matter',
	framework: 'esp-matter',
	chips: ['esp32', 'esp32s3', 'esp32c3', 'esp32c6'],
	defaults,
	pins: [{ key: 'resetGpio', label: 'Factory reset button', optional: true }],
	validate,
	activate({ use, config, project, role }) {
		use(network);
		use(configuratorEditors).register(Editor);
		use(firmware).register(() => {
			const { passcode, discriminator } = setupCode(config, project.name, role.id);
			const manual = formatManualCode(manualPairingCode(passcode, discriminator));
			const qr = qrCodePayload({ passcode, discriminator });
			return {
				sdkconfig: {
					CONFIG_BT_ENABLED: true,
					CONFIG_BT_NIMBLE_ENABLED: true,
					CONFIG_BT_NIMBLE_EXT_ADV: false,
					CONFIG_BT_NIMBLE_HCI_EVT_BUF_SIZE: 70,
					CONFIG_ENABLE_ESP32_BLE_CONTROLLER: true,
					// BLE is only needed to pair: free its memory afterwards.
					CONFIG_USE_BLE_ONLY_FOR_COMMISSIONING: true,
					CONFIG_ENABLE_CHIP_SHELL: false,
					CONFIG_CUSTOM_COMMISSIONABLE_DATA_PROVIDER: true,
					CONFIG_CHIP_PROJECT_CONFIG: 'main/matter_project_config.h',
					CONFIG_LWIP_IPV6_AUTOCONFIG: true,
					CONFIG_MBEDTLS_HKDF_C: true,
					CONFIG_ESP_MAIN_TASK_STACK_SIZE: 6144
				},
				defines: {
					MESP_MATTER_PASSCODE: passcode,
					MESP_MATTER_DISCRIMINATOR: discriminator,
					MESP_MATTER_RESET_GPIO: Number(config.resetGpio)
				},
				sources: {
					'espm_node.cpp': nodeCpp,
					'espm_node.h': nodeH,
					'matter_project_config.h': projectConfigH(String(config.vendorName), project.name)
				},
				hooks: {
					includes: ['#include "espm_node.h"'],
					preStart: ['mesp_node_init();'],
					postStart: ['mesp_node_start();']
				},
				notes: [
					`Matter pairing code: ${manual} (QR code: ${qr}). Pair over Bluetooth with any Matter controller; with Wi-Fi configured the device also shows up on your network.`,
					'The device uses Matter test certificates (like all DIY devices): controllers warn that it is uncertified. A Matter Thread Hub needs “Test PAA only” as its attestation trust store to pair it.',
					Number(config.resetGpio) >= 0
						? `Factory reset (forget all pairings): hold GPIO${config.resetGpio} low for 10 s.`
						: 'No factory reset button: erase the flash to pair the device again from scratch.'
				]
			};
		});
	}
} satisfies FeatureDef<MatterDeviceConfig>;
