import { configuratorEditors, firmware } from './services';
import type {
	FeatureDef,
	Contribution,
	GenerateContext,
	FeatureIssue,
	Validate
} from '../../types';
import Editor, { FLASH_SIZES, PSRAM_MODES, CONSOLES } from './configurator/Editor.svelte';

/** Smallest flash with room for two app slots (`FeatureDef.otaSlots`). */
export const OTA_MIN_FLASH_MB = 8;

/** The board's PSRAM as configured in "Chip & memory": `none`, `quad` or `octal`. */
export function psramMode(ctx: GenerateContext): string {
	const psram = ctx.featureConfig('device')?.psram ?? 'board';
	return psram === 'board' ? ctx.board.psram : String(psram);
}

/** The board's flash size as configured in "Chip & memory". */
export function flashMB(ctx: GenerateContext): number {
	const size = ctx.featureConfig('device')?.flashSize ?? 'board';
	return size === 'board' ? ctx.board.flashSizeMB : Number(size);
}

