const defaults = () => ({ flashSize: 'board', psram: 'board', console: 'board' });
export type DeviceConfig = ReturnType<typeof defaults>;

const validate: Validate<DeviceConfig> = ({ config }) => {
	const errors: FeatureIssue<DeviceConfig>[] = [];
	if (!FLASH_SIZES.some((o) => o.value === config.flashSize))
		errors.push({ field: 'flashSize', message: 'Flash size: invalid option.' });
	if (!PSRAM_MODES.some((o) => o.value === config.psram))
		errors.push({ field: 'psram', message: 'PSRAM: invalid option.' });
	if (!CONSOLES.some((o) => o.value === config.console))
		errors.push({ field: 'console', message: 'Log console: invalid option.' });
	return errors;
};

/**
 * Chip-level settings every role has: flash size, PSRAM, serial console and the partition table
 * (with two app slots when a feature of the chip needs them, `otaSlots`). Defaults come from the
 * selected board.
 */
export default {
	id: 'device',
	dir: 'core',
	name: 'Chip & memory',
	description: 'Flash size, PSRAM and serial console of the board.',
	category: 'core',
	always: true,
	defaults,
	validate,
	activate(ctx) {
		ctx.use(configuratorEditors).register(Editor);
		ctx.use(firmware).register(() => {
			const { board, config, role } = ctx;
			const flash = flashMB(ctx);
			const psram = psramMode(ctx);
			const console =
				config.console === 'board'
					? board.usb === 'usb-serial-jtag'
						? 'usb'
						: 'uart'
					: config.console;
			const ota = ctx.features.some((f) => f.otaSlots) && flash >= OTA_MIN_FLASH_MB;

			const sdk: Contribution['sdkconfig'] = {
				[`CONFIG_ESPTOOLPY_FLASHSIZE_${flash}MB`]: true,
				CONFIG_PARTITION_TABLE_CUSTOM: true,
				CONFIG_PARTITION_TABLE_CUSTOM_FILENAME: 'partitions.csv'
			};
			if (console === 'usb') sdk.CONFIG_ESP_CONSOLE_USB_SERIAL_JTAG = true;
			else sdk.CONFIG_ESP_CONSOLE_UART_DEFAULT = true;

			const result: Contribution = {
				sdkconfig: sdk,
				defines: { MESP_FLASH_MB: flash },
				sources: {},
				rootFiles: { 'partitions.csv': partitionTable(flash, ota, 48) },
				notes: []
			};

			if (psram !== 'none') {
				Object.assign(sdk, {
					CONFIG_SPIRAM: true,
					[psram === 'octal' ? 'CONFIG_SPIRAM_MODE_OCT' : 'CONFIG_SPIRAM_MODE_QUAD']: true,
					CONFIG_SPIRAM_SPEED_80M: true,
					CONFIG_SPIRAM_MALLOC_ALWAYSINTERNAL: 512,
					CONFIG_SPIRAM_MALLOC_RESERVE_INTERNAL: 16384,
					CONFIG_SPIRAM_TRY_ALLOCATE_WIFI_LWIP: true
				});
				if (role.framework === 'esp-matter') {
					Object.assign(sdk, {
						CONFIG_SPIRAM_ALLOW_BSS_SEG_EXTERNAL_MEMORY: true,
						CONFIG_BT_NIMBLE_MEM_ALLOC_MODE_EXTERNAL: true,
						CONFIG_ESP_MATTER_MEM_ALLOC_MODE_EXTERNAL: true,
						CONFIG_MBEDTLS_EXTERNAL_MEM_ALLOC: true
					});
					result.sources!['linker.lf'] = LINKER_LF;
				}
			}
			return result;
		});
	}
} satisfies FeatureDef<DeviceConfig>;

/** Partition table for a role, derived from the device config. */
export function partitionTable(flashMB: number, ota: boolean, nvsKB: number): string {
	const rows: string[][] = [['# Name', 'Type', 'SubType', 'Offset', 'Size', 'Flags']];
	rows.push(['nvs', 'data', 'nvs', '', `${nvsKB}K`, '']);
	if (ota) rows.push(['otadata', 'data', 'ota', '', '8K', '']);
	rows.push(['phy_init', 'data', 'phy', '', '4K', '']);
	// App partitions start at 0x20000 (64 KB aligned) and must fit in flash.
	const available = flashMB * 1024 - 128 - 64;
	if (ota) {
		const slot = Math.floor(available / 2 / 64) * 64;
		rows.push(['ota_0', 'app', 'ota_0', '0x20000', `${slot}K`, '']);
		rows.push(['ota_1', 'app', 'ota_1', '', `${slot}K`, '']);
	} else {
		rows.push(['factory', 'app', 'factory', '0x20000', `${Math.floor(available / 64) * 64}K`, '']);
	}
	return rows.map((r) => r.join(', ').replace(/(, )+$/, '')).join('\n') + '\n';
}
