<!--
  Accounts of the hub's web interface (admins only). Admins may do everything; users see and
  control only the paired devices they have grants for – per device, optionally per endpoint –
  and the scenes of others granted to them.
  Passwords are generated by the hub and shown once; the user sets their own at the first login.
  Accounts are created and edited in a dialog.
-->
<script lang="ts">
	import {
		api,
		Badge,
		Button,
		Code,
		Dialog,
		errorText,
		Input,
		Notice,
		Poll,
		Segmented
	} from '#sdk/device-ui';
	import { visibleEndpoints } from './clusters';
	import type { Scene } from './automations';
	import { typeName, type Node } from './matter';

	/** `{"n<node>": level, "n<node>.<endpoint>": level, "s<scene>": level}`, level 0 none, 1 read, 2 write. */
	type Grants = Record<string, number>;

	interface Account {
		id: number;
		name: string;
		admin: boolean;
		/** The admin whose password is set in the app. */
		builtin?: boolean;
		/** Still has a generated password. */
		mustChange?: boolean;
		grants?: Grants;
		/** Only in the answer to creating it or resetting its password. */
		password?: string;
	}

	interface Draft {
		/** Missing: a new account. */
		id?: number;
		name: string;
		admin: boolean;
		grants: Grants;
	}

	const accounts = new Poll<{ accounts: Account[] }>('/api/v1/auth/accounts', 60000);
	const nodes = new Poll<{ nodes: Node[] }>('/api/v1/controller/nodes', 30000);
	// Admins get every scene; missing on hubs without automations.
	const scenes = new Poll<{ scenes: Scene[] }>('/api/v1/controller/scenes', 60000);

	let draft = $state<Draft>();
	let expanded = $state<Record<number, boolean>>({});
	let confirmDelete = $state(false);
	let busy = $state(false);
	let status = $state<{ tone: 'ok' | 'err'; text: string }>();
	/** A generated password, shown once. */
	let secret = $state<{ name: string; password: string }>();

	const LEVELS = [
		{ value: '0', label: 'None' },
		{ value: '1', label: 'Read' },
		{ value: '2', label: 'Write' }
	];
	const ENDPOINT_LEVELS = [{ value: '', label: 'As device' }, ...LEVELS];
	const ROLES = [
		{ value: 'user', label: 'User' },
		{ value: 'admin', label: 'Admin' }
	];

	function summary(a: Account): string {
		if (a.builtin) return 'Password set in the app';
		if (a.admin) return 'All devices and settings';
		const granted = Object.entries(a.grants ?? {})
			.filter(([, level]) => level > 0)
			.map(([res]) => res.split('.')[0]);
		const devices = new Set(granted.filter((res) => res.startsWith('n'))).size;
		const shared = new Set(granted.filter((res) => res.startsWith('s'))).size;
		const text = devices ? `${devices} device${devices === 1 ? '' : 's'}` : 'No devices';
		return shared ? `${text}, ${shared} scene${shared === 1 ? '' : 's'}` : text;
	}

	function edit(a?: Account) {
		draft = a
			? { id: a.id, name: a.name, admin: a.admin, grants: { ...a.grants } }
			: { name: '', admin: false, grants: {} };
		confirmDelete = false;
		status = undefined;
		secret = undefined;
	}

	function setGrant(res: string, value: string) {
		if (!draft) return;
		if (value === '') delete draft.grants[res];
		else draft.grants[res] = Number(value);
	}

	/** Scenes of others: its own the account may use anyway. */
	const otherScenes = $derived(
		(scenes.current?.scenes ?? []).filter((sc) => sc.owner !== draft?.name)
	);

	/** "None" on a device or scene is the default; on an endpoint it overrides the device's grant. */
	const stored = (grants: Grants) =>
		Object.fromEntries(
			Object.entries(grants).filter(([res, level]) => res.includes('.') || level > 0)
		);

	async function run(action: () => Promise<unknown>, done: string) {
		busy = true;
		status = undefined;
		secret = undefined;
		try {
			const res = (await action()) as Account | undefined;
			if (res?.password) secret = { name: res.name, password: res.password };
			else status = { tone: 'ok', text: done };
			draft = undefined;
			await accounts.refresh();
		} catch (e) {
			status = { tone: 'err', text: errorText(e) };
		} finally {
			busy = false;
		}
	}

	function save() {
		const d = draft;
		if (!d) return;
		const body = { admin: d.admin, grants: stored(d.grants) };
		const name = d.name.trim().toLowerCase();
		void run(
			() =>
				d.id === undefined
					? api('/api/v1/auth/accounts', { body: { ...body, name } })
					: api(`/api/v1/auth/accounts/${d.id}`, { method: 'PUT', body }),
			`${name} saved.`
		);
	}

	function resetPassword() {
		const d = draft;
		if (d?.id === undefined) return;
		void run(
			() => api(`/api/v1/auth/accounts/${d.id}`, { method: 'PUT', body: { resetPassword: true } }),
			`New password for ${d.name}.`
		);
	}

	function remove() {
		const d = draft;
		if (d?.id === undefined) return;
		void run(
			() => api(`/api/v1/auth/accounts/${d.id}`, { method: 'DELETE' }),
			`${d.name} deleted.`
		);
	}
</script>

{#if accounts.current}
	<ul class="grid gap-1.5">
		{#each accounts.current.accounts as a (a.id)}
			<li class="flex items-center gap-2 rounded-lg border border-border bg-surface-2/50 px-3 py-2">
				<span class="truncate font-medium">{a.name}</span>
				<Badge tone={a.admin ? 'accent' : 'neutral'}>{a.admin ? 'admin' : 'user'}</Badge>
				<span class="min-w-0 truncate text-xs text-muted">{summary(a)}</span>
				{#if a.mustChange}<Badge tone="warn">password not changed yet</Badge>{/if}
				{#if !a.builtin}
					<Button size="sm" variant="ghost" class="ml-auto" onclick={() => edit(a)}>Edit</Button>
				{/if}
			</li>
		{/each}
	</ul>
	<Button class="mt-3" onclick={() => edit()}>New account</Button>
{:else if accounts.error}
	<p class="text-sm text-err">{accounts.error}</p>
{/if}

<Dialog
	wide
	bind:open={() => !!draft, (v) => !v && (draft = undefined)}
	title={draft?.id === undefined ? 'New account' : `Account ${draft.name}`}
	onsubmit={save}
>
	{#if draft}
		<div class="grid gap-3">
			{#if draft.id === undefined}
				<label class="grid gap-1 text-sm">
					<span class="text-muted">Name</span>
					<Input
						autocomplete="off"
						autocapitalize="none"
						maxlength={23}
						pattern="[a-z0-9._\-]+"
						title="Lowercase letters, digits, . _ -"
						placeholder="anna"
						required
						bind:value={draft.name}
					/>
				</label>
			{/if}
			{#if draft.id === undefined}
				<p class="m-0 text-sm text-muted">
					The hub generates a password, shown once after saving. It must be changed at the first
					login.
				</p>
			{/if}
			<div class="grid gap-1 text-sm">
				<span class="text-muted">Role</span>
				<Segmented
					label="Role"
					value={draft.admin ? 'admin' : 'user'}
					options={ROLES}
					onchange={(v) => {
						if (draft) draft.admin = v === 'admin';
					}}
				/>
			</div>

			{#if draft.admin}
				<p class="m-0 text-sm text-muted">
					Admins see and control every device, pair and remove devices, manage accounts and change
					the hub’s settings.
				</p>
			{:else}
				<div class="grid gap-2">
					<span class="text-sm text-muted">Devices: read shows them, write also controls them.</span
					>
					{#each nodes.current?.nodes ?? [] as node (node.id)}
						{@const res = `n${node.id}`}
						{@const endpoints = visibleEndpoints(node)}
						<div class="grid gap-2 rounded-md border border-border bg-surface px-2.5 py-2">
							<div class="flex flex-wrap items-center gap-2">
								<span class="min-w-0 flex-1 truncate text-sm font-medium">{node.name}</span>
								<div class="w-full sm:w-56">
									<Segmented
										label="Access to {node.name}"
										value={String(draft.grants[res] ?? 0)}
										options={LEVELS}
										onchange={(v) => setGrant(res, v)}
									/>
								</div>
							</div>
							{#if endpoints.length > 1 || expanded[node.id]}
								<button
									type="button"
									class="justify-self-start text-xs font-medium text-accent"
									onclick={() => (expanded[node.id] = !expanded[node.id])}
									>{expanded[node.id]
										? 'Hide endpoints'
										: `Per endpoint (${endpoints.length})`}</button
								>
							{/if}
							{#if expanded[node.id]}
								{#each endpoints as ep (ep.id)}
									{@const epRes = `${res}.${ep.id}`}
									<div class="flex flex-wrap items-center gap-2 sm:pl-3">
										<span class="min-w-0 flex-1 truncate text-xs text-muted"
											>{typeName(ep) || 'Endpoint'} · {ep.id}</span
										>
										<div class="w-full sm:w-72">
											<Segmented
												label="Access to endpoint {ep.id} of {node.name}"
												value={epRes in draft.grants ? String(draft.grants[epRes]) : ''}
												options={ENDPOINT_LEVELS}
												onchange={(v) => setGrant(epRes, v)}
											/>
										</div>
									</div>
								{/each}
							{/if}
						</div>
					{:else}
						<p class="m-0 text-sm text-muted">{nodes.error ?? 'No paired devices yet.'}</p>
					{/each}
				</div>
				{#if otherScenes.length}
					<div class="grid gap-2">
						<span class="text-sm text-muted"
							>Scenes of others: read shows and runs them, write also edits them. A scene only sets
							the devices the account may control.</span
						>
						{#each otherScenes as scene (scene.id)}
							{@const res = `s${scene.id}`}
							<div
								class="flex flex-wrap items-center gap-2 rounded-md border border-border bg-surface px-2.5 py-2"
							>
								<span class="min-w-0 flex-1 truncate text-sm font-medium"
									>{scene.name} <span class="font-normal text-muted">· {scene.owner}</span></span
								>
								<div class="w-full sm:w-56">
									<Segmented
										label="Access to scene {scene.name}"
										value={String(draft.grants[res] ?? 0)}
										options={LEVELS}
										onchange={(v) => setGrant(res, v)}
									/>
								</div>
							</div>
						{/each}
					</div>
				{/if}
			{/if}

			{#if status?.tone === 'err'}<Notice tone="err">{status.text}</Notice>{/if}
		</div>
	{/if}
	{#snippet footer()}
		<Button variant="primary" type="submit" disabled={busy}>{busy ? 'Saving…' : 'Save'}</Button>
		<Button variant="ghost" onclick={() => (draft = undefined)}>Cancel</Button>
		{#if draft?.id !== undefined}
			<Button variant="ghost" disabled={busy} onclick={resetPassword}>Reset password</Button>
			{#if confirmDelete}
				<Button variant="danger" class="ml-auto" disabled={busy} onclick={remove}
					>Delete {draft.name}</Button
				>
			{:else}
				<Button variant="ghost" class="ml-auto text-err" onclick={() => (confirmDelete = true)}
					>Delete…</Button
				>
			{/if}
		{/if}
	{/snippet}
</Dialog>
<Dialog
	bind:open={() => !!secret, (v) => !v && (secret = undefined)}
	title="Password for {secret?.name ?? ''}"
>
	{#if secret}
		<div class="grid gap-2 text-sm">
			<span>Shown once – pass it on securely:</span>
			<Code class="justify-self-start rounded bg-surface-2 px-2 py-1 text-base text-fg select-all"
				>{secret.password}</Code
			>
			<span class="text-xs text-muted"
				>{secret.name} sets their own password at the first login.</span
			>
		</div>
	{/if}
	{#snippet footer()}
		<Button variant="primary" onclick={() => (secret = undefined)}>Done</Button>
	{/snippet}
</Dialog>
{#if status && !draft}<div class="mt-3"><Notice tone={status.tone}>{status.text}</Notice></div>{/if}
